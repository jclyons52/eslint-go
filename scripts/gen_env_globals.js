'use strict';
// gen_env_globals.js — generates globals_env.go from the exact data ESLint 8
// uses for `env`: @eslint/eslintrc's Legacy.environments (which wraps the
// `globals` npm package).
//
// Run from the eslint-go repo root with the oracle's node_modules available:
//   node scripts/gen_env_globals.js
const fs = require('fs');
const path = require('path');

const eslintDir = process.env.ESLINT_ORACLE || './oracle/node_modules/eslint';
const eslintrc = require(path.join(process.cwd(), 'oracle/node_modules/@eslint/eslintrc'));
const eslintrcPkg = require(path.join(process.cwd(), 'oracle/node_modules/@eslint/eslintrc/package.json'));
const globalsPkg = require(path.join(process.cwd(), 'oracle/node_modules/globals/package.json'));

const environments = eslintrc.Legacy.environments;
const out = {};
const envNames = [];

for (const [envId, env] of environments.entries()) {
    if (!env || !env.globals) continue;
    const names = {};
    for (const [name, value] of Object.entries(env.globals)) {
        if (value === 'off') continue;
        names[name] = (value === 'writable' || value === true) ? 'writable' : 'readonly';
    }
    out[envId] = names;
    envNames.push(envId);
}

envNames.sort();
const ordered = {};
for (const id of envNames) ordered[id] = out[id];

const json = JSON.stringify(ordered);

const file = `package eslint

// Code generated by scripts/gen_env_globals.js — DO NOT EDIT.
//
// Environment globals for the \`env\` config key, taken from
// @eslint/eslintrc@${eslintrcPkg.version} Legacy.environments (${environments.size} envs),
// which is what ESLint 8 uses; its data comes from the globals npm package
// (globals@${globalsPkg.version}).
//
// Values are "readonly" / "writable", matching ConfigOps.normalizeConfigGlobal.

import (
	"encoding/json"
	"sort"
	"sync"
)

// envGlobalsJSON is the env → {global name → access} table as JSON.
const envGlobalsJSON = \`${json}\`

var (
	envGlobalsOnce sync.Once
	envGlobalsData map[string]map[string]string
)

// EnvGlobals returns the globals an environment contributes (name → access),
// or nil for an unknown environment.
func EnvGlobals(env string) map[string]string {
	envGlobalsOnce.Do(func() {
		envGlobalsData = map[string]map[string]string{}
		if err := json.Unmarshal([]byte(envGlobalsJSON), &envGlobalsData); err != nil {
			panic("eslint: invalid embedded env globals: " + err.Error())
		}
	})
	return envGlobalsData[env]
}

// EnvNames returns the supported environment ids (sorted).
func EnvNames() []string {
	EnvGlobals("") // ensure the table is loaded
	out := make([]string, 0, len(envGlobalsData))
	for id := range envGlobalsData {
		out = append(out, id)
	}
	sort.Strings(out)
	return out
}
`;

const target = path.join(process.cwd(), 'globals_env.go');
fs.writeFileSync(target, file);
let total = 0;
for (const id of envNames) total += Object.keys(ordered[id]).length;
console.log(`wrote ${target}: ${envNames.length} envs, ${total} global entries, ${json.length} bytes`);
